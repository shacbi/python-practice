# Python Dictionary Basics

student = {
    "name": "Shacbi",
    "age": 20,
    "language": "Python"
}

# Get a value
print(student["name"])
print(student["age"])
print(student["language"])

# Change a value
student["age"] = 21
print(student)

# Add a new key and value
student["country"] = "Somalia"
print(student)